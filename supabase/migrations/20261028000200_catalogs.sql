-- Catálogos. Las políticas RLS se crean en la migración de profiles (necesitan los helpers).
create table public.branches (
  id smallint primary key,
  code text not null unique,
  name text not null,
  active boolean not null default true
);

create table public.channels (
  id smallint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true,
  sort smallint not null default 0
);

-- Producto de interés = categoría (Celulares es una sola), sin marcas ni modelos. La línea para metas se deriva del grupo.
create table public.products (
  id integer generated by default as identity primary key,
  name text not null unique,
  product_group public.product_group not null,
  line public.product_line not null generated always as (
    case when product_group = 'phones' then 'phones'::public.product_line else 'appliances'::public.product_line end
  ) stored,
  sort smallint not null default 0,
  active boolean not null default true
);

create table public.lost_reasons (
  id smallint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true
);

create table public.agenda_strategies (
  id smallint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true
);

create table public.settings (
  key text primary key,
  value jsonb not null
);

alter table public.branches enable row level security;
alter table public.channels enable row level security;
alter table public.products enable row level security;
alter table public.lost_reasons enable row level security;
alter table public.agenda_strategies enable row level security;
alter table public.settings enable row level security;

