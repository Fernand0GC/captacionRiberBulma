-- Organización comercial (spec 003, 2026-11-17): catálogo de tres niveles Estrategia → Canal → Subcanal, con
-- horario sugerido de mañana y de tarde por subcanal. Es independiente del catálogo de canales de captación
-- (FR-006). Lectura: cualquier usuario activo. Escritura: solo Sistemas. Nunca se borra; se desactiva.

create table public.org_strategies (
  id smallint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) between 2 and 60),
  sort smallint not null default 0,
  active boolean not null default true
);

create table public.org_channels (
  id smallint generated by default as identity primary key,
  strategy_id smallint not null references public.org_strategies (id),
  name text not null check (length(trim(name)) between 2 and 60),
  sort smallint not null default 0,
  active boolean not null default true,
  unique (strategy_id, name),
  -- Para la llave compuesta de las asignaciones: el canal pertenece a esa estrategia.
  unique (id, strategy_id)
);

create table public.org_subchannels (
  id smallint generated by default as identity primary key,
  channel_id smallint not null references public.org_channels (id),
  name text not null check (length(trim(name)) between 2 and 80),
  sort smallint not null default 0,
  active boolean not null default true,
  morning_start time,
  morning_end time,
  afternoon_start time,
  afternoon_end time,
  unique (channel_id, name),
  unique (id, channel_id),
  -- Cada horario va completo (inicio y fin) o vacío, y termina después de empezar.
  constraint org_subchannels_morning check (
    (morning_start is null and morning_end is null)
    or (morning_start is not null and morning_end is not null and morning_end > morning_start)),
  constraint org_subchannels_afternoon check (
    (afternoon_start is null and afternoon_end is null)
    or (afternoon_start is not null and afternoon_end is not null and afternoon_end > afternoon_start))
);
create index org_subchannels_channel_idx on public.org_subchannels (channel_id, sort);
create index org_channels_strategy_idx on public.org_channels (strategy_id, sort);

alter table public.org_strategies enable row level security;
alter table public.org_channels enable row level security;
alter table public.org_subchannels enable row level security;

revoke all on public.org_strategies, public.org_channels, public.org_subchannels from anon;
revoke delete, truncate on public.org_strategies, public.org_channels, public.org_subchannels from authenticated;
grant select, insert, update on public.org_strategies, public.org_channels, public.org_subchannels to authenticated;

create policy org_strategies_read on public.org_strategies for select to authenticated using (public.app_is_active());
create policy org_channels_read on public.org_channels for select to authenticated using (public.app_is_active());
create policy org_subchannels_read on public.org_subchannels for select to authenticated using (public.app_is_active());

create policy org_strategies_admin on public.org_strategies for all to authenticated
  using (public.app_is_active() and public.app_role() = 'admin') with check (public.app_is_active() and public.app_role() = 'admin');
create policy org_channels_admin on public.org_channels for all to authenticated
  using (public.app_is_active() and public.app_role() = 'admin') with check (public.app_is_active() and public.app_role() = 'admin');
create policy org_subchannels_admin on public.org_subchannels for all to authenticated
  using (public.app_is_active() and public.app_role() = 'admin') with check (public.app_is_active() and public.app_role() = 'admin');

